/**
 * 密码生成器对话框。
 * - 生成结果明文展示:重新生成在 leadingIcon,复制在 trailingIcon
 * - 长度 EnhancedSlider (8-32),选项变更自动重新生成
 * - 字符集 4 个 EnhancedCheckbox,"排除易混淆字符" EnhancedSwitch
 * - "使用此密码"按钮回填
 */
@Composable
fun PasswordGeneratorDialog(
    initial: PasswordGeneratorOptions = PasswordGeneratorOptions(),
    generator: PasswordGenerator,
    onDismiss: () -> Unit,
    onConfirm: (String) -> Unit,
) {
    var options by remember { mutableStateOf(initial) }
    var generated by remember { mutableStateOf(generator.generate(initial)) }
    val clipboard = LocalClipboardManager.current

    val charsetInvalid = !options.isValid

    // 选项(长度/字符集/易混淆)变更后自动重新生成,无需手动点刷新
    LaunchedEffect(options) {
        generated = generator.generate(options)
    }

    EnhancedAlertDialog(
        visible = true,
        onDismissRequest = onDismiss,
        title = {
            Text(
                text = stringResource(R.string.password_vault_generator_title),
                style = MaterialTheme.typography.titleMedium,
                fontWeight = FontWeight.Bold,
            )
        },
        text = {
            Column(
                modifier = Modifier.fillMaxWidth(),
                verticalArrangement = Arrangement.spacedBy(12.dp),
            ) {
                GlassOutlinedTextField(
                    value = generated,
                    onValueChange = {},
                    readOnly = true,
                    modifier = Modifier.fillMaxWidth(),
                    singleLine = true,
                    shape = RoundedCornerShape(12.dp),
                    leadingIcon = {
                        IconButton(onClick = { generated = generator.generate(options) }) {
                            Icon(
                                imageVector = com.t8rin.imagetoolbox.core.resources.Icons.Outlined.Refresh,
                                contentDescription = stringResource(R.string.password_vault_generator_regenerate),
                            )
                        }
                    },
                    trailingIcon = {
                        IconButton(
                            onClick = { clipboard.setText(AnnotatedString(generated)) }
                        ) {
                            Icon(
                                imageVector = com.t8rin.imagetoolbox.core.resources.Icons.Rounded.ContentCopy,
                                contentDescription = stringResource(R.string.password_vault_copy_password),
                            )
                        }
                    },
                )

                Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                    ) {
                        Text(
                            text = stringResource(R.string.password_vault_generator_length),
                            style = MaterialTheme.typography.bodyMedium,
                        )
                        Text(
                            text = options.length.toString(),
                            style = MaterialTheme.typography.bodyMedium,
                            fontWeight = FontWeight.SemiBold,
                        )
                    }
                    EnhancedSlider(
                        value = options.length.toFloat(),
                        onValueChange = { options = options.copy(length = it.toInt()) },
                        valueRange = 8f..32f,
                        steps = 23,
                    )
                }

                CharsetToggle(
                    label = stringResource(R.string.password_vault_generator_uppercase),
                    checked = options.includeUppercase,
                    onCheckedChange = { options = options.copy(includeUppercase = it) },
                )
                CharsetToggle(
                    label = stringResource(R.string.password_vault_generator_lowercase),
                    checked = options.includeLowercase,
                    onCheckedChange = { options = options.copy(includeLowercase = it) },
                )
                CharsetToggle(
                    label = stringResource(R.string.password_vault_generator_digits),
                    checked = options.includeDigits,
                    onCheckedChange = { options = options.copy(includeDigits = it) },
                )
                CharsetToggle(
                    label = stringResource(R.string.password_vault_generator_symbols),
                    checked = options.includeSymbols,
                    onCheckedChange = { options = options.copy(includeSymbols = it) },
                )

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically,
                ) {
                    Text(
                        text = stringResource(R.string.password_vault_generator_exclude_ambiguous),
                        style = MaterialTheme.typography.bodyMedium,
                    )
                    EnhancedSwitch(
                        checked = options.excludeAmbiguous,
                        onCheckedChange = { options = options.copy(excludeAmbiguous = it) },
                    )
                }

                if (charsetInvalid) {
                    Text(
                        text = stringResource(R.string.password_vault_generator_charset_invalid),
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.error,
                    )
                }
            }
        },
        confirmButton = {
            ConfirmButton(enabled = !charsetInvalid && generated.isNotEmpty()) {
                onConfirm(generated)
            }
        },
        dismissButton = {
            CancelButton { onDismiss() }
        },
    )
}

@Composable
private fun CharsetToggle(
    label: String,
    checked: Boolean,
    onCheckedChange: (Boolean) -> Unit,
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .height(36.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        EnhancedCheckbox(
            checked = checked,
            onCheckedChange = onCheckedChange,
        )
        Spacer(modifier = Modifier.size(6.dp))
        Text(
            text = label,
            style = MaterialTheme.typography.bodyMedium,
        )
    }
}
